"""Grand-canonical fluctuation-ratio bridge from the validated live EOS result.

This is a derived observable, not a new fit: it consumes only the authenticated
thermodynamic/static q=0 result, then evaluates kappa_2/kappa_1=T*chi_T/n.
The input artifact is regenerated by nvg_thermo_static_zero_mode_closure.py.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any, Mapping, Sequence

import mpmath as mp

HERE = Path(__file__).resolve().parent
INPUT_PATH = HERE / "nvg_thermo_static_zero_mode_results.json"
SCHEMA_VERSION = "nvg-gc-fluctuation-ratio.v1"
STATUS_PASS = "PASS_DERIVED_GC_FLUCTUATION_RATIO"
STATUS_FAIL = "FAIL_DERIVED_GC_FLUCTUATION_RATIO"
MATCH_LIMIT = mp.mpf("2e-7")

import nvg_thermo_static_zero_mode_closure as closure  # noqa: E402


def _mp(value: Any) -> mp.mpf:
    return value if isinstance(value, mp.mpf) else mp.mpf(str(value))


def _number(value: Any) -> str:
    value = _mp(value)
    if not mp.isfinite(value):
        raise ValueError("nonfinite output")
    return mp.nstr(value, 30)


def _payload_bytes(value: Mapping[str, Any]) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")


def _rows(source_rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows = []
    for source in source_rows:
        t = _mp(source["T_MeV"])
        n = _mp(source["state"]["n_MeV3"])
        chi_eos = _mp(source["thermodynamic_side"]["chi_eos_MeV2"])
        chi_static = _mp(source["static_q0_side"]["chi_static_MeV2"])
        if t <= 0 or n <= 0 or chi_eos <= 0 or chi_static <= 0:
            raise ValueError("fluctuation relation requires positive T, density and susceptibility")
        c2_c1_eos = t * chi_eos / n
        c2_c1_static = t * chi_static / n
        rel = abs(c2_c1_eos - c2_c1_static) / max(abs(c2_c1_eos), abs(c2_c1_static), mp.mpf("1e-40"))
        rows.append({
            "anchor": source["anchor"],
            "model": source["model"],
            "T_MeV": source["T_MeV"],
            "mu_MeV": source["mu_MeV"],
            "n_MeV3": source["state"]["n_MeV3"],
            "chi_T_MeV2": source["thermodynamic_side"]["chi_eos_MeV2"],
            "chi_static_q0_MeV2": source["static_q0_side"]["chi_static_MeV2"],
            "kappa2_per_volume_MeV3": _number(t * chi_eos),
            "kappa2_over_kappa1": _number(c2_c1_eos),
            "kappa2_over_kappa1_from_static_q0": _number(c2_c1_static),
            "eos_static_ratio_relative_error": _number(rel),
            "pass": bool(rel < MATCH_LIMIT),
        })
    return rows


def _build_result(input_path: Path = INPUT_PATH) -> dict[str, Any]:
    root = Path(closure.__file__).resolve().parents[1]
    try:
        input_label = input_path.resolve().relative_to(root).as_posix()
    except ValueError:
        input_label = str(input_path.resolve())
    raw = input_path.read_bytes()
    upstream = json.loads(raw)
    if not closure.validate_result(upstream):
        raise ValueError("upstream live EOS/static-q=0 artifact failed validation")
    primary = _rows(upstream["primary_rows"])
    refined = _rows(upstream["refined_rows"])
    paired: dict[tuple[str, str], dict[str, mp.mpf]] = {}
    for row in primary:
        paired.setdefault((row["anchor"], row["mu_MeV"]), {})[row["model"]] = _mp(row["kappa2_over_kappa1"])
    contrasts = []
    for (anchor, mu), models in sorted(paired.items()):
        w8, u16 = models["w8"], models["u16"]
        difference = abs(w8 - u16) / max(abs(w8), abs(u16), mp.mpf("1e-40"))
        contrasts.append({"anchor": anchor, "mu_MeV": mu, "w8_over_u16_relative_difference": _number(difference)})
    max_error = max(_mp(r["eos_static_ratio_relative_error"]) for r in primary + refined)
    max_contrast = max(_mp(r["w8_over_u16_relative_difference"]) for r in contrasts)
    result: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "status": STATUS_PASS,
        "independent_evidence_weight": 0.0,
        "fit_used": False,
        "input_artifact": input_label,
        "input_artifact_sha256": hashlib.sha256(raw).hexdigest(),
        "relation": "grand-canonical equilibrium: kappa2/V=T*(partial n/partial mu)_T; kappa1/V=n; therefore kappa2/kappa1=T*chi_T/n",
        "units": {"T": "MeV", "n": "MeV^3", "chi_T": "MeV^2", "kappa2/V": "MeV^3", "kappa2/kappa1": "dimensionless"},
        "coverage": {"primary_rows": len(primary), "refined_rows": len(refined), "paired_W8_U16_contrasts": len(contrasts)},
        "interpretation_limits": [
            "This is an equilibrium grand-canonical identity applied to the validated model output, not an experimental measurement or an independent test of NVG.",
            "Finite-volume conservation, detector acceptance, diffusion, nonequilibrium evolution and particle-to-proton mapping are not included.",
            "A small W8/U16 difference on this grid means this observable does not distinguish those model variants here.",
        ],
        "primary_rows": primary,
        "refined_rows": refined,
        "model_contrasts": contrasts,
        "controls": {
            "coverage": {"pass": len(primary) == 8 and len(refined) == 8 and len(contrasts) == 4},
            "eos_vs_static_fluctuation_identity": {"maximum_relative_error": _number(max_error), "pass": bool(max_error < MATCH_LIMIT and all(r["pass"] for r in primary + refined))},
            "model_contrasts_finite": {"maximum_relative_difference": _number(max_contrast), "pass": bool(mp.isfinite(max_contrast))},
        },
        "source_sha256": {"producer": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(), "upstream_producer": hashlib.sha256(Path(closure.__file__).resolve().read_bytes()).hexdigest()},
    }
    result["all_controls_pass"] = all(control["pass"] for control in result["controls"].values())
    result["status"] = STATUS_PASS if result["all_controls_pass"] else STATUS_FAIL
    result["integrity_sha256"] = hashlib.sha256(_payload_bytes(result)).hexdigest()
    return result


def validate_result(result: Any, input_path: Path = INPUT_PATH) -> bool:
    try:
        if not isinstance(result, Mapping) or result.get("schema_version") != SCHEMA_VERSION:
            return False
        return dict(result) == _build_result(input_path)
    except (ArithmeticError, KeyError, OSError, TypeError, ValueError, json.JSONDecodeError):
        return False


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=INPUT_PATH)
    parser.add_argument("--output", type=Path, default=HERE / "nvg_gc_fluctuation_ratio_results.json")
    parser.add_argument("--validate", type=Path)
    args = parser.parse_args(argv)
    if args.validate:
        valid = validate_result(json.loads(args.validate.read_text(encoding="utf-8")), args.input)
        print("PASS" if valid else "FAIL")
        return 0 if valid else 1
    result = _build_result(args.input)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(result["status"])
    return 0 if result["all_controls_pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
